import { expect, test } from './test'
import { OMP_CHAT_PANE, gradientPng } from './scenario.mjs'
import { rewindItems } from '../fixtures/ompRewind'

// Only the existing fake pane and routed neutral transcript are used. Never edit live sessions.
test('committed rewinds restore nested history and images on a phone without hiding the handoff or current request', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  const items = rewindItems()
  await page.route('**/api/chat?*', route => route.fulfill({ json: { available: true, file: '/home/user/rewind.jsonl', token: 'rewind-browser', start: 0, end: 1000, items } }))
  await page.route('**/api/chat/image?*', route => route.fulfill({ contentType: 'image/png', body: gradientPng() }))
  await page.goto(`/#/a/${OMP_CHAT_PANE}`)
  const chat = page.locator('.chat')
  const parent = chat.locator('.omp-rewind').filter({ hasText: 'Package handoff retained.' })
  await expect(parent).toBeVisible()
  await expect(chat.locator('.omp-rewind')).toHaveCount(2)
  await expect(chat.getByText('Retired child analysis.', { exact: true })).toHaveCount(0)
  await expect(chat.getByText('Keep the current request visible.', { exact: true })).toBeVisible()
  await expect(parent.getByRole('button')).toHaveAttribute('aria-expanded', 'false')
  const hit = await parent.getByRole('button').boundingBox()
  expect(hit!.height).toBeGreaterThanOrEqual(44)
  expect(hit!.width).toBeGreaterThanOrEqual(44)
  await parent.getByRole('button').click()
  await expect(chat.getByText('Retired child analysis.', { exact: true })).toBeVisible()
  const search = chat.locator('.omp-rewind').filter({ hasText: 'Search decision retained.' })
  await expect(search).toBeVisible()
  await expect(chat.getByText('Retired locating explanation.', { exact: true })).toHaveCount(0)
  await search.getByRole('button').click()
  await expect(chat.getByText('Retired locating explanation.', { exact: true })).toBeVisible()
  const image = chat.locator('.process-images .msg-img')
  await expect(image).toBeVisible()
  await expect.poll(() => image.evaluate(img => (img as HTMLImageElement).naturalWidth)).toBe(240)
  await image.click()
  await expect(page.locator('.lightbox img')).toBeVisible()
  await page.keyboard.press('Escape')
  await search.locator('.omp-rewind-material summary').click()
  await expect(search.locator('.omp-rewind-material pre')).toContainText('<img src=x onerror=alert(1)>')
  await expect(search.locator('.omp-rewind-material img')).toHaveCount(0)
  await expect(chat.locator('.omp-rewind.no-cut')).toContainText('Context unchanged')
  await expect(chat.locator('.omp-rewind.no-cut button')).toHaveCount(0)
  const rails = await parent.evaluate(el => ({ cut: getComputedStyle(el).borderLeftColor, neutral: getComputedStyle(document.querySelector('.chat .omp-rewind.no-cut')!).borderLeftColor }))
  expect(rails.cut).not.toBe(rails.neutral)
  await parent.getByRole('button').click()
  await expect(chat.getByText('Retired child analysis.', { exact: true })).toHaveCount(0)
  await expect(chat.locator('.process-images')).toHaveCount(0)
  await expect(chat.getByText('Current response remains visible.', { exact: true })).toBeVisible()
  await page.reload()
  await expect(chat.locator('.omp-rewind')).toHaveCount(2)
  await expect(parent.getByRole('button')).toHaveAttribute('aria-expanded', 'false')
})

test('loading an authoritative earlier page resolves a partial rewind without folding unrelated requests', async ({ page }) => {
  const items = rewindItems()
  await page.route('**/api/chat?*', route => {
    const older = new URL(route.request().url()).searchParams.has('before')
    return route.fulfill({ json: older
      ? { available: true, file: '/home/user/rewind-pages.jsonl', older: true, start: 0, end: 350, items: items.slice(0, 4) }
      : { available: true, file: '/home/user/rewind-pages.jsonl', token: 'rewind-pages', start: 350, end: 1000, items: items.slice(4) } })
  })
  await page.goto(`/#/a/${OMP_CHAT_PANE}`)
  const chat = page.locator('.chat')
  await expect(chat.locator('.omp-rewind-partial')).toHaveCount(2)
  await expect(chat.getByText('Retired child analysis.', { exact: true })).toBeVisible()
  await expect(chat.locator('.omp-rewind-toggle')).toHaveCount(0)
  await chat.getByRole('button', { name: 'Load earlier messages' }).click()
  await expect(chat.locator('.omp-rewind-partial')).toHaveCount(0)
  await expect(chat.locator('.omp-rewind')).toHaveCount(2)
  await expect(chat.getByText('Retired child analysis.', { exact: true })).toHaveCount(0)
  await expect(chat.getByText('Review the example module.', { exact: true })).toBeVisible()
  await expect(chat.getByText('Keep the current request visible.', { exact: true })).toBeVisible()
})

test('the desktop output panel shares committed rewind semantics and independently expands real retired output', { tag: '@chromium-desktop' }, async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.route('**/api/chat?*', route => route.fulfill({ json: { available: true, file: '/home/user/rewind-output.jsonl', token: 'rewind-output', start: 0, end: 1000, items: rewindItems() } }))
  await page.goto(`/#/a/${OMP_CHAT_PANE}`)
  const output = page.locator('.conversation-output')
  await expect(output).toBeVisible()
  await expect(output.locator('.omp-rewind')).toHaveCount(2)
  await expect(output.locator('.conversation-output-tool')).toHaveCount(0)
  const parent = output.locator('.omp-rewind').filter({ hasText: 'Package handoff retained.' })
  await parent.getByRole('button').click()
  const search = output.locator('.omp-rewind').filter({ hasText: 'Search decision retained.' })
  await expect(search).toBeVisible()
  await search.getByRole('button').click()
  const tool = output.locator('.conversation-output-tool')
  await tool.locator('summary').click()
  await expect(tool.locator('.conversation-output-result')).toHaveText('Retired file output.')
  await expect(output.locator('.conversation-output-terminal')).toContainText('Current output.')
  await expect(page.locator('.chat .omp-rewind')).toHaveCount(2)
  await parent.getByRole('button').click()
  await expect(output.locator('.conversation-output-tool')).toHaveCount(0)
  await expect(output.locator('.omp-rewind')).toHaveCount(2)
  await expect(output.locator('.conversation-output-terminal')).toContainText('Current output.')
})
